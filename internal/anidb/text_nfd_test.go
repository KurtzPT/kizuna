// A title normalizes the same precomposed (NFC, as AniDB writes it) and
// decomposed (NFD, as macOS writes file names).
func TestNormalizeNFCAndNFD(t *testing.T) {
	for _, c := range nfd {
		for _, around := range [][2]string{{"", ""}, {"ab", "cd"}} {
			nfc, dec := around[0]+c.nfc+around[1], around[0]+c.nfd+around[1]
			if a, b := Normalize(nfc), Normalize(dec); a != b {
				t.Errorf("%U: Normalize(%q) = %q, but NFD %q gives %q", []rune(c.nfc)[0], nfc, a, dec, b)
			}
		}
	}
	// Hangul: every syllable against its jamo (the Unicode decomposition).
	for s := rune(hangulS); s < hangulS+countL*countV*countT; s++ {
		i := s - hangulS
		jamo := string([]rune{hangulL + i/(countV*countT), hangulV + i%(countV*countT)/countT})
		if tail := i % countT; tail > 0 {
			jamo += string(hangulT + tail)
		}
		if a, b := Normalize(string(s)), Normalize(jamo); a != b {
			t.Errorf("%U: Normalize = %q, but its jamo %q give %q", s, a, jamo, b)
		}
	}
}

// Voicing stays: が is another kana than か, in both forms.
func TestNormalizeKeepsKanaVoicing(t *testing.T) {
	for _, c := range []struct{ in, want string }{
		{"が", "が"}, {"が", "が"}, {"ぱ", "ぱ"}, {"ぱ", "ぱ"}, {"ヴ", "ヴ"}, {"ヴ", "ヴ"},
		{"がっこうぐらし", "がっこうぐらし"}, {"がっこうぐらし", "がっこうぐらし"},
		{"あ゙", "あ"}, // no voiced あ: the mark goes, as in NFC
	} {
		if got := Normalize(c.in); got != c.want {
			t.Errorf("Normalize(%q) = %q, want %q", c.in, got, c.want)
		}
	}
	if Normalize("か") == Normalize("が") {
		t.Error("か and が normalize the same")
	}
}

